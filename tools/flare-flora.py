#!/usr/bin/env python3
"""
Builds the vegetation / decoration atlas from the Flare tilesets (CC-BY-SA 3.0, see CREDITS.md):
trees, pines, dead trees (green and snowy), tents, tombstones and the well. Each picked tile is cropped
to its alpha, scaled by the same factor as the creature sheets (so a Flare tree keeps its size next to a
Flare hero) and packed into one WebP. The client draws them as camera-facing instanced billboards inside
the 3D scene, so they go through the ASCII post-process like everything else.

Usage: python3 tools/flare-flora.py <flare-game checkout> <out .webp> <out .ts>
"""
import json
import os
import sys
from PIL import Image

FLARE, OUT_IMG, OUT_TS = sys.argv[1], sys.argv[2], sys.argv[3]
CORE = os.path.join(FLARE, 'mods/fantasycore')
SCALE = 0.45
M_PER_SRC_PX = 0.0118  # same as tools/flare-sheets.py
SHEET_W = 2048

PICKS = {
    'tree': [('grassland', i) for i in (240, 241, 242, 243, 252, 253, 254, 255)],
    'pine': [('grassland', i) for i in (248, 249, 250, 251)],
    'deadtree': [('grassland', i) for i in (244, 245, 246, 247)],
    'deadtree_snow': [('snowplains', i) for i in (244, 245, 246, 247)],
    'tent': [('grassland', i) for i in (72, 75)],
    'grave': [('grassland', i) for i in (140, 141, 142, 143)],
    'well': [('grassland', 296)],
    'stump': [('grassland', 137)],
    'signpost': [('grassland', 138), ('grassland', 139)],
    'campfire': [('grassland', 102)],
}


def tiles_of(name):
    """tile index -> (image, x, y, w, h, ox, oy); a def file can switch images between sections."""
    out = {}
    cache = {}
    img = None
    for line in open(os.path.join(CORE, 'tilesetdefs', f'tileset_{name}.txt'), encoding='utf-8'):
        line = line.strip()
        if line.startswith('img='):
            path = os.path.join(CORE, line[4:])
            img = cache.setdefault(path, Image.open(path).convert('RGBA'))
        if line.startswith('tile=') and img is not None:
            v = list(map(int, line[5:].split(',')[:7]))
            out.setdefault(v[0], (img, *v[1:]))
    return out


sets = {n: tiles_of(n) for n in ('grassland', 'snowplains')}
crops = []  # (key, image, anchor x, anchor y)
for key, picks in PICKS.items():
    for ts, idx in picks:
        img, x, y, w, h, ox, oy = sets[ts][idx]
        part = img.crop((x, y, x + w, y + h))
        part = part.resize((max(1, round(w * SCALE)), max(1, round(h * SCALE))), Image.LANCZOS)
        bb = part.getchannel('A').point(lambda v: 255 if v > 12 else 0).getbbox() or (0, 0, 1, 1)
        crops.append((key, part.crop(bb), ox * SCALE - bb[0], oy * SCALE - bb[1]))

order = sorted(range(len(crops)), key=lambda n: -crops[n][1].size[1])
rects = [None] * len(crops)
x = y = shelf = 0
for n in order:
    w, h = crops[n][1].size
    if x + w + 1 > SHEET_W:
        x, y, shelf = 0, y + shelf + 1, 0
    rects[n] = (x, y)
    x += w + 1
    shelf = max(shelf, h)
sheet = Image.new('RGBA', (SHEET_W, y + shelf + 1))
for n, (_k, im, _ax, _ay) in enumerate(crops):
    sheet.alpha_composite(im, rects[n])
sheet.save(OUT_IMG, 'WEBP', quality=80, alpha_quality=85, method=6)

kinds = {}
for n, (key, im, ax, ay) in enumerate(crops):
    w, h = im.size
    kinds.setdefault(key, []).append([rects[n][0], rects[n][1], w, h, round(ax, 1), round(ay, 1)])
print(f'flora atlas {sheet.size[0]}x{sheet.size[1]} {os.path.getsize(OUT_IMG) // 1024} KB, {len(crops)} sprites')
with open(OUT_TS, 'w') as f:
    f.write('// Generated by tools/flare-flora.py from the Flare tilesets (CC-BY-SA 3.0) — do not edit by hand.\n')
    f.write('/** Variants per kind: [x, y, w, h, anchorX, anchorY] in the atlas (px). */\n')
    f.write(f'export const FLORA = {{ w: {SHEET_W}, h: {sheet.size[1]}, mpp: {round(M_PER_SRC_PX / SCALE, 5)}, kinds: {json.dumps(kinds, separators=(",", ":"))} }} as const;\n')
